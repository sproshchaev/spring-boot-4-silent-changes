CREATE TABLE orders (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku        VARCHAR(64)    NOT NULL,
    status     VARCHAR(16)    NOT NULL,
    total      DECIMAL(12, 2) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

